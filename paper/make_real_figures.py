def field_maps():
    import geopandas as gpd
    paths = {o: os.path.join(RES, "spatial", o, "field.csv") for o in OUTCOMES}
    fields = {o: pd.read_csv(p) for o, p in paths.items() if os.path.exists(p)}
    if not fields:
        return
    fig, axes = plt.subplots(1, len(fields), figsize=(5.5 * len(fields), 5.6), constrained_layout=True)
    axes = np.atleast_1d(axes)
    vmax = max(np.nanpercentile(np.abs(f.loc[f.observed, "field"]), 99) for f in fields.values())
    w = gpd.read_file(BORDERS)
    for ax, (o, fl) in zip(axes, fields.items()):
        fl = fl[fl.observed]
        xlim = (fl.lon.min() - 1, fl.lon.max() + 1); ylim = (fl.lat.min() - 1, fl.lat.max() + 1)
        w.plot(ax=ax, color="#ecebe7", edgecolor="none", zorder=0)
        lon0, lat0 = fl.lon.min(), fl.lat.min()
        nx = int(round((fl.lon.max() - lon0) / 0.5)) + 1; ny = int(round((fl.lat.max() - lat0) / 0.5)) + 1
        g = np.full((ny, nx), np.nan)
        g[np.round((fl.lat - lat0) / 0.5).astype(int), np.round((fl.lon - lon0) / 0.5).astype(int)] = fl.field
        im = ax.imshow(g, origin="lower", extent=[lon0 - .25, lon0 + nx * .5 - .25, lat0 - .25, lat0 + ny * .5 - .25],
                       cmap=DIVERGING, norm=TwoSlopeNorm(0, -vmax, vmax), interpolation="nearest", zorder=1)
        w.boundary.plot(ax=ax, color="#3d3d3d", linewidth=0.35, zorder=2)
        ax.set_xlim(*xlim); ax.set_ylim(*ylim)
        ax.set_title(f"{o.capitalize()}: residual field $\\hat w(s)$", loc="left", color=INK)
        ax.set_aspect("equal"); ax.set_xlabel("longitude"); ax.set_ylabel("latitude")
        for s in ("top", "right"):
            ax.spines[s].set_visible(False)
    cb = fig.colorbar(im, ax=list(axes), shrink=0.75, label="posterior mean (logit scale)")
    cb.outline.set_visible(False)
    fig.savefig(os.path.join(FIG, "real_field.png"), dpi=200)
    plt.close(fig)
    print("wrote real_field.png")


