def table_xgb():
    paths = sorted(glob.glob(os.path.join(RES, "xgb", "metrics_*.json")))
    m = {}
    for p in paths:
        j = load(p)
        m[(j["mode"], j["outcome"])] = j
    known = [k for k, _ in XGB_MODES]
    modes = XGB_MODES + [(k, tex_escape(k)) for k in sorted({k for k, _ in m} - set(known))]
    rows, prev = [], None
    for mode, lab in modes:
        for o in ("Conflict", "Unrest"):
            j = m.get((mode, o))
            if j is None:
                continue
            if prev is not None and prev != mode:
                rows.append("\\addlinespace")
            prev = mode
            n, pr = j.get("n_test_rows"), j.get("test_prevalence")
            ntxt = "--" if n is None else f"{n / 1e6:.2f}M"
            ptxt = "--" if pr is None else f"{100 * pr:.2f}\\%"
            rows.append(f"{lab} & {o} & {ntxt} & {ptxt} & "
                        f"{j.get('rounds', '--')} & {f(j.get('auc_pr'))} & {f(j.get('auc_pr_border_cells'))} & "
                        f"{f(j.get('auc_pr_interior_cells'))} & {f(j.get('persistence_auc_pr'))} \\\\")
            SUMMARY.append(("real_xgb.tex", f"{mode:13s} {o:8s} rows={n} prev={f(pr, 4)} "
                            f"trees={j.get('rounds')} AUC-PR={f(j.get('auc_pr'))} dup={f(j.get('auc_pr_border_cells'))} "
                            f"other={f(j.get('auc_pr_interior_cells'))} persistence={f(j.get('persistence_auc_pr'))} "
                            f"cal.logscore={f(get(j, 'calibrated', 'log_score'), 4)} AUC-ROC={f(j.get('auc_roc'))}"))
    head = ("Pipeline & Outcome & Test rows & Prevalence & Trees & AUC-PR & "
            "\\multicolumn{2}{c}{AUC-PR by cell} & Persistence \\\\\n"
            "\\cmidrule(lr){7-8}\n"
            " & & & & & & dup.\\ in original & other cells & AUC-PR \\\\")
    write("real_xgb.tex", tabular("@{}llrrrcccc@{}", head, rows), paths)


def table_diag():
    cf = compare_files()
    rows = []
    for i, (o, p) in enumerate(cf.items()):
        c = load(p)
        if i:
            rows.append("\\addlinespace")
        for k in ordered(c["models"]):
            r = c["models"][k]
            mo, bo = r.get("residual_moran", {}), r.get("residual_border", {})
            pv = mo.get("p_value")
            ptxt = "--" if pv is None else (f"$\\le${pv:.3f}" if pv <= 0.001 + 1e-12 else f"{pv:.3f}")
            rows.append(f"{o.capitalize()} & {label(k)} & {f(mo.get('I'))} & {ptxt} & "
                        f"{f(bo.get('within_country'))} & {f(bo.get('across_border'))} \\\\")
            SUMMARY.append(("real_diag.tex", f"{o:8s} {k:16s} MoranI={f(mo.get('I'))} p={pv} "
                            f"within={f(bo.get('within_country'))} across={f(bo.get('across_border'))} "
                            f"(pairs within={bo.get('n_within')}, across={bo.get('n_across')})"))
    head = ("Outcome & Model & Moran's $I$ & $p$ & \\multicolumn{2}{c}{Neighbour residual corr.} \\\\\n"
            "\\cmidrule(lr){5-6}\n & & & & within country & across border \\\\")
    write("real_diag.tex", tabular("@{}llcccc@{}", head, rows), list(cf.values()))


def table_hybrid():
    cf = compare_files()
    data = {o: load(p) for o, p in cf.items()}
    allm = [r for c in data.values() for r in c["models"].values()]
    has_country = any(get(r, "logscore_diff_vs_ref", "se_country") is not None for r in allm)
    has_onset = any(isinstance(r.get("onset"), dict) for r in allm)
    rows = []
    for i, (o, c) in enumerate(data.items()):
        ref = c.get("reference")
        if i:
            rows.append("\\addlinespace")
        for k in ordered(c["models"]):
            r = c["models"][k]
            d = r.get("logscore_diff_vs_ref") or {}
            sc = lambda x: "--" if x is None else f"{1e3 * x:.2f}"
            if k == ref:
                diff = ["\\multicolumn{" + str(1 + has_country) + "}{c}{reference}"]
            else:
                diff = [f"{sc(d.get('mean'))} ({sc(d.get('se_cell'))})"]
                if has_country:
                    diff.append(f"({sc(d.get('se_country'))})")
            cells = [o.capitalize(), label(k), f(r.get("log_score"), 4), f(r.get("brier"), 4),
                     f(r.get("auc_pr")), f(r.get("auc_roc"))] + diff
            if has_onset:
                on = r.get("onset") or {}
                cells += [f(on.get("log_score"), 4), f(on.get("auc_pr"))]
            rows.append(" & ".join(cells) + " \\\\")
            SUMMARY.append(("real_hybrid.tex", f"{o:8s} {k:16s} log={f(r.get('log_score'), 5)} brier={f(r.get('brier'), 5)} "
                            f"AUC-PR={f(r.get('auc_pr'))} AUC-ROC={f(r.get('auc_roc'))} "
                            f"dlog x1e3={sc(d.get('mean'))} se_cell={sc(d.get('se_cell'))} "
                            f"se_country={sc(d.get('se_country'))}"
                            + (f" onset={r.get('onset')}" if has_onset else "")))
        ncol = 6 + 1 + has_country + 2 * has_onset
        pers = c.get("persistence_auc_pr")
        prow = [o.capitalize(), "Persistence (past 4 weeks)", "--", "--", f(pers), "--"] + ["--"] * (ncol - 6)
        rows.append(" & ".join(prow) + " \\\\")
        SUMMARY.append(("real_hybrid.tex", f"{o:8s} persistence AUC-PR={f(pers)}; rows={c.get('n_rows')} "
                        f"cells={c.get('n_cells')} prevalence={f(c.get('prevalence'), 4)} reference={ref}"))
    dhead = "\\multicolumn{" + str(1 + has_country) + "}{c}{$\\Delta$ log score $\\times 10^3$ (SE)}"
    sub = " & ".join(["by cell"] + (["by country"] if has_country else []))
    head = "Outcome & Model & Log score & Brier & AUC-PR & AUC-ROC & " + dhead
    if has_onset:
        head += " & \\multicolumn{2}{c}{Onset rows}"
    head += " \\\\\n"
    c0 = 7
    head += f"\\cmidrule(lr){{{c0}-{c0 + has_country}}}"
    if has_onset:
        head += f"\\cmidrule(lr){{{c0 + 1 + has_country}-{c0 + 2 + has_country}}}"
    head += "\n & & & & & & " + sub + (" & Log score & AUC-PR" if has_onset else "") + " \\\\"
    spec = "@{}llcccc" + "c" * (1 + has_country) + "cc" * has_onset + "@{}"
    write("real_hybrid.tex", tabular(spec, head, rows), list(cf.values()))


def table_field():
    paths = outcome_inputs("spatial", "summary.json")
    rows = []
    labs = {"field": "$u + w$", "iid": "$u$ + iid cell effects"}
    for p in paths:
        s = load(p)
        o = s.get("outcome", os.path.basename(os.path.dirname(p)))
        for k in sorted(s.get("models", {}), key=lambda x: (x != "field", x)):
            h = s["models"][k].get("hyper", {})
            rng = h.get("field.range_km")
            rows.append(f"{o.capitalize()} & {labs.get(k, tex_escape(k))} & {'--' if rng is None else f'{rng:.0f}'} & "
                        f"{f(h.get('field.sd'), 2)} & {f(h.get('cell.sd'), 2)} & {f(h.get('country.sd'), 2)} \\\\")
            extra = {kk: vv for kk, vv in h.items() if kk not in ("field.range_km", "field.sd", "cell.sd", "country.sd")}
            SUMMARY.append(("real_field.tex", f"{o:8s} {k:6s} hyper={json.dumps({kk: round(vv, 3) for kk, vv in h.items()})}"
                            f" log_ml={f(s['models'][k].get('log_ml'), 1)}" + (f" UNTABULATED={extra}" if extra else "")))
        SUMMARY.append(("real_field.tex", f"{o:8s} region={s.get('region')} cells={s.get('cells')} "
                        f"barrier_cells={s.get('barrier_cells')} rows={s.get('rows')} test_rows={s.get('test_rows')} "
                        f"folds={s.get('folds')} offset_trees_per_fold={s.get('offset_rounds_per_fold')}"))
    head = ("Outcome & Latent terms & $\\hat\\rho_w$ (km) & $\\hat\\sigma_w$ & $\\hat\\sigma_{\\rm cell}$ & "
            "$\\hat\\sigma_u$ \\\\")
    write("real_field.tex", tabular("@{}llcccc@{}", head, rows), paths)


def table_boxes():
    spaths = outcome_inputs("spatial", "summary.json")
    fpaths = outcome_inputs("spatial", "field.csv")
    S = {load(p).get("outcome", os.path.basename(os.path.dirname(p))): load(p) for p in spaths}
    outs = [o for o in OUTCOMES if o in S]
    boxes = {o: get(S[o], "models", "field", "boxes") or {} for o in outs}
    names = []
    for o in outs:
        names += [b for b in boxes[o] if b not in names]
    rows = []
    for b in names:
        any_box = next(boxes[o][b] for o in outs if b in boxes[o])
        x0, x1, y0, y1 = any_box["box"]
        cells = [BOX_NAMES.get(b, tex_escape(b).replace("\\_", " ")), f"{x0:g} to {x1:g}", f"{y0:g} to {y1:g}", str(any_box["cells"])]
        for o in outs:
            r = boxes[o].get(b)
            cells += ["--", "--"] if r is None else [f"{r['mean']:.2f} ({r['sd']:.2f})", f"{r['p_positive']:.2f}"]
            if r is not None:
                SUMMARY.append(("real_boxes.tex", f"{o:8s} {b:20s} cells={r['cells']} mean={r['mean']:.2f} "
                                f"sd={r['sd']:.2f} P(>0)={r['p_positive']:.3f}"))
        rows.append(" & ".join(cells) + " \\\\")
    # summary not based on chosen boxes: share of observed cells with P(w(s) > 0) > 0.95 or < 0.05
    share = {}
    for p in fpaths:
        o = os.path.basename(os.path.dirname(p))
        fl = pd.read_csv(p)
        if "p_positive" not in fl:
            continue
        fl = fl[fl.observed.astype(bool)]
        share[o] = (len(fl), float((fl.p_positive > 0.95).mean()), float((fl.p_positive < 0.05).mean()))
        SUMMARY.append(("real_boxes.tex", f"{o:8s} all {len(fl)} observed cells: share P(w>0)>0.95 = "
                        f"{share[o][1]:.3f}, share P(w>0)<0.05 = {share[o][2]:.3f}"))
    if share:
        rows.append("\\midrule")
        n = next(iter(share.values()))[0]
        for j, lab in ((1, "Share of cells with $P\\{w(s) > 0\\} > 0.95$"), (2, "Share of cells with $P\\{w(s) > 0\\} < 0.05$")):
            cells = [f"\\multicolumn{{3}}{{@{{}}l}}{{{lab}}}", str(n)]
            for o in outs:
                cells += ["\\multicolumn{2}{c}{" + (f"{share[o][j]:.3f}" if o in share else "--") + "}"]
            rows.append(" & ".join(cells) + " \\\\")
    head = ("Region & Longitude & Latitude & Cells & "
            + " & ".join(f"\\multicolumn{{2}}{{c}}{{{o.capitalize()}}}" for o in outs) + " \\\\\n"
            + "".join(f"\\cmidrule(lr){{{5 + 2 * i}-{6 + 2 * i}}}" for i in range(len(outs))) + "\n"
            + " & & & & " + " & ".join("mean (SD) & $P(>0)$" for _ in outs) + " \\\\")
    write("real_boxes.tex", tabular("@{}lllr" + "cc" * len(outs) + "@{}", head, rows), spaths + fpaths)


def write_summary(path):
    with open(path, "w") as fh:
        cur = None
        for t, line in SUMMARY:
            if t != cur:
                fh.write(f"\n## {t}\n"); cur = t
            fh.write(f"- {line}\n")
    print("summary:", path)


if __name__ == "__main__":
    import sys
    field_maps(); variograms()
    table_xgb(); table_diag(); table_hybrid(); table_field(); table_boxes()
    if len(sys.argv) > 1:
        write_summary(sys.argv[1])
    else:
        for t, line in SUMMARY:
            print(t, "|", line)
