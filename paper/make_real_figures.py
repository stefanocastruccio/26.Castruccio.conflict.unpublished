import hashlib
import json
import os

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from matplotlib.colors import LinearSegmentedColormap, TwoSlopeNorm

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
RES = os.path.join(ROOT, "results_real")
FIG = os.path.join(HERE, "figures")
TAB = os.path.join(HERE, "tables")
BORDERS = os.path.join(HERE, "data", "ne_50m_countries.geojson")
os.makedirs(FIG, exist_ok=True); os.makedirs(TAB, exist_ok=True)

OUTCOMES = ("conflict", "unrest")

BLUE, ORANGE, INK, MUTED, GRID = "#2a78d6", "#eb6834", "#1a1a1a", "#6b6b6b", "#e4e3df"
DIVERGING = LinearSegmentedColormap.from_list("bgr", ["#1f5fae", "#8fb6e6", "#f0efec", "#ef9a86", "#b7321f"])
plt.rcParams.update({"font.size": 9, "axes.edgecolor": MUTED, "axes.labelcolor": INK,
                     "xtick.color": MUTED, "ytick.color": MUTED, "axes.titlesize": 10})

XGB_MODES = [("original", "As published"),
             ("dedup", "Original procedure, repaired table"),
             ("corrected", "Corrected"),
             ("corrected_te", "Corrected + cell event rate")]

MODEL_LABELS = {"xgb": "XGBoost, corrected",
                "xgb_te": "XGBoost + cell event rate",
                "xgb_crossfit": "XGBoost, cross-fitted by country",
                "hybrid_iid": "Cross-fitted XGBoost + $u$ + iid cell effects",
                "hybrid_field": "Cross-fitted XGBoost + $u + w$",
                "hybrid_field_iid": "Cross-fitted XGBoost + $u + w$ + iid cell effects"}
MODEL_ORDER = ["xgb", "xgb_te", "xgb_crossfit", "hybrid_iid", "hybrid_field", "hybrid_field_iid"]

BOX_NAMES = {"eastern_DRC": "Eastern DRC", "northern_Mozambique": "Northern Mozambique",
             "Syria_Iraq": "Syria and Iraq", "Lake_Chad": "Lake Chad", "central_Sahel": "Central Sahel",
             "Horn_of_Africa": "Horn of Africa", "Arabian_interior": "Arabian interior",
             "western_Congo_basin": "Western Congo basin", "southern_Africa": "Southern Africa"}

# summary for the text: list of (table file, line)
SUMMARY = []


# ----------------------------------------------------------------------------- helpers
def rel(p):
    return os.path.relpath(p, ROOT)


def sha(p):
    with open(p, "rb") as fh:
        return hashlib.sha256(fh.read()).hexdigest()[:12]


def provenance(paths):
    lines = ["% Generated by paper/make_real_figures.py; do not edit by hand.", "% Inputs (sha256 prefix):"]
    lines += [f"%   {rel(p)}  {sha(p)}" for p in paths]
    return "\n".join(lines) + "\n"


def load(p):
    with open(p) as fh:
        return json.load(fh)


def get(d, *keys):
    """Nested lookup that returns None if any key is missing."""
    for k in keys:
        if not isinstance(d, dict) or k not in d or d[k] is None:
            return None
        d = d[k]
    return d


def f(x, d=3):
    if x is None or (isinstance(x, float) and not np.isfinite(x)):
        return "--"
    return f"{x:.{d}f}"


def tex_escape(s):
    return s.replace("_", r"\_")


def label(key):
    return MODEL_LABELS.get(key, tex_escape(key))


def ordered(models):
    return [k for k in MODEL_ORDER if k in models] + sorted(k for k in models if k not in MODEL_ORDER)


def write(name, body, inputs):
    with open(os.path.join(TAB, name), "w") as fh:
        fh.write(provenance(inputs) + body)
    print("wrote", name)


def tabular(spec, head, rows):
    return ("\\begin{tabular}{" + spec + "}\n\\toprule\n" + head + "\n\\midrule\n"
            + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")


def outcome_inputs(sub, name):
    return [p for p in (os.path.join(RES, sub, o, name) for o in OUTCOMES) if os.path.exists(p)]


def compare_files():
    return {o: os.path.join(RES, "compare", f"compare_{o}.json") for o in OUTCOMES
            if os.path.exists(os.path.join(RES, "compare", f"compare_{o}.json"))}


# ----------------------------------------------------------------------------- figures
def field_maps():
    import geopandas as gpd
    paths = {o: os.path.join(RES, "spatial", o, "field.csv") for o in OUTCOMES}
    fields = {o: pd.read_csv(p) for o, p in paths.items() if os.path.exists(p)}
    if not fields:
        return
    fig, axes = plt.subplots(1, len(fields), figsize=(5.5 * len(fields), 5.6), constrained_layout=True)
    axes = np.atleast_1d(axes)
    vmax = max(np.nanpercentile(np.abs(f.loc[f.observed, "field"]), 99) for f in fields.values())
    w = gpd.read_file(BORDERS)
    for ax, (o, fl) in zip(axes, fields.items()):
        fl = fl[fl.observed]
        xlim = (fl.lon.min() - 1, fl.lon.max() + 1); ylim = (fl.lat.min() - 1, fl.lat.max() + 1)
        w.plot(ax=ax, color="#ecebe7", edgecolor="none", zorder=0)
        lon0, lat0 = fl.lon.min(), fl.lat.min()
        nx = int(round((fl.lon.max() - lon0) / 0.5)) + 1; ny = int(round((fl.lat.max() - lat0) / 0.5)) + 1
        g = np.full((ny, nx), np.nan)
        g[np.round((fl.lat - lat0) / 0.5).astype(int), np.round((fl.lon - lon0) / 0.5).astype(int)] = fl.field
        im = ax.imshow(g, origin="lower", extent=[lon0 - .25, lon0 + nx * .5 - .25, lat0 - .25, lat0 + ny * .5 - .25],
                       cmap=DIVERGING, norm=TwoSlopeNorm(0, -vmax, vmax), interpolation="nearest", zorder=1)
        w.boundary.plot(ax=ax, color="#3d3d3d", linewidth=0.35, zorder=2)
        ax.set_xlim(*xlim); ax.set_ylim(*ylim)
        ax.set_title(f"{o.capitalize()}: residual field $\\hat w(s)$", loc="left", color=INK)
        ax.set_aspect("equal"); ax.set_xlabel("longitude"); ax.set_ylabel("latitude")
        for s in ("top", "right"):
            ax.spines[s].set_visible(False)
    cb = fig.colorbar(im, ax=list(axes), shrink=0.75, label="posterior mean (logit scale)")
    cb.outline.set_visible(False)
    fig.savefig(os.path.join(FIG, "real_field.png"), dpi=200)
    plt.close(fig)
    print("wrote real_field.png")


def variograms():
    fig, ax = plt.subplots(figsize=(5.5, 3.4), constrained_layout=True)
    for o, col in zip(OUTCOMES, (BLUE, ORANGE)):
        p = os.path.join(RES, "spatial", o, "variogram.csv")
        if not os.path.exists(p):
            continue
        v = pd.read_csv(p)
        ax.plot(v.dist_km, v.gamma, color=col, lw=2, marker="o", ms=4)
        ax.annotate(o.capitalize(), (v.dist_km.iloc[-1], v.gamma.iloc[-1]), xytext=(4, 0),
                    textcoords="offset points", va="center", color=INK)
    ax.set_xlabel("great-circle distance (km)"); ax.set_ylabel("semivariance of cell residuals")
    ax.grid(color=GRID, lw=0.6); ax.set_axisbelow(True)
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    fig.savefig(os.path.join(FIG, "real_variogram.png"), dpi=200)
    plt.close(fig)
    print("wrote real_variogram.png")


