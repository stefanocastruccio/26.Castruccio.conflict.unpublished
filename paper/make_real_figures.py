"""Figures and tables for the application section, generated only from the committed
result files in results_real/:

  results_real/xgb/metrics_<mode>_<Outcome>.json      -> tables/real_xgb.tex
  results_real/spatial/<outcome>/summary.json         -> tables/real_field.tex, tables/real_boxes.tex
  results_real/spatial/<outcome>/field.csv            -> figures/real_field.png, tables/real_boxes.tex
  results_real/spatial/<outcome>/variogram.csv        -> figures/real_variogram.png
  results_real/compare/compare_<outcome>.json         -> tables/real_diag.tex, tables/real_hybrid.tex

Every table starts with a LaTeX comment that lists its input files and their SHA-256
prefixes, so a stale table can be detected. Keys that are absent from a result file
(for example standard errors clustered by country, or onset scores, which are only
written by later versions of compare.py) are skipped or printed as '--'.

Run from the repository root:  python paper/make_real_figures.py"""
